package com.andrey.readerlite

/** Одно слово из профиля интересов: как оно выглядит и насколько важно. */
data class Interest(val word: String, val weight: Double)

/**
 * Значимые слова заголовка. Подбор идёт по словам, а не по смыслу, поэтому
 * отбрасываем служебные и «новостные» слова, а окончания срезаем, чтобы
 * «автомобиль», «автомобили» и «автомобилей» считались одним словом.
 */
object Keywords {

    private val STOP_WORDS = setOf(
        "который", "которая", "которое", "которые", "которых", "которым", "может", "могут", "будет",
        "будут", "после", "также", "более", "менее", "чтобы", "этого", "этой", "этот", "этом", "этих",
        "году", "года", "годы", "время", "заявил", "заявила", "заявили", "сообщил", "сообщила",
        "сообщили", "сообщает", "рассказал", "рассказала", "рассказали", "назвал", "назвала",
        "назвали", "стало", "стал", "стала", "стали", "новый", "новая", "новое", "новые", "нового",
        "новых", "своих", "свой", "своей", "свою", "почему", "когда", "через", "между", "против",
        "около", "ради", "всех", "всего", "только", "даже", "очень", "можно", "нужно", "самый",
        "самые", "первый", "первые", "теперь", "сегодня", "вчера", "завтра", "россии", "россия",
        "россиян", "россияне", "рублей", "рубля", "человек", "людей", "раскрыли", "раскрыл",
        "объяснил", "объяснили", "эксперт", "эксперты", "новости", "фото", "видео", "главное",
        "день", "дней", "неделе", "месяц", "мнение", "тысяч", "процентов", "почти", "из-за",
        "пока", "уже", "ещё", "еще", "какие", "какой", "каких", "такой", "такие", "будто", "весь",
        "хотят", "хочет", "может", "стоит", "станет", "начал", "начали", "решил", "решили",
        "получил", "получили", "показал", "показали", "появился", "появились", "появилась",
    )

    private val ENDING = Regex(
        "(иями|ями|ами|ого|его|ому|ему|ыми|ими|ией|ия|ий|ый|ой|ая|яя|ое|ее|ые|ие|ую|юю|ых|их|ов|ев|ей|ам|ям|ах|ях|ом|ем|а|я|о|е|ы|и|у|ю|ь)$"
    )

    private val STOP_STEMS = STOP_WORDS.map { stem(it) }.toSet()

    fun stem(word: String): String {
        val w = word.lowercase()
        if (w.length <= 4) return w
        val cut = ENDING.find(w)?.range?.first ?: return w
        return if (cut >= 4) w.substring(0, cut) else w
    }

    /** Пары «основа → слово как в заголовке», без повторов. */
    fun extract(title: String): List<Pair<String, String>> =
        Regex("[\\p{L}\\p{N}]+(?:-[\\p{L}\\p{N}]+)?").findAll(title)
            .map { it.value }
            .filter { it.length >= 4 && !it.all(Char::isDigit) && it.lowercase() !in STOP_WORDS }
            .map { stem(it) to it }
            .filter { it.first !in STOP_STEMS }
            .distinctBy { it.first }
            .toList()
}
